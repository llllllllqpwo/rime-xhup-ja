# 单键假名（あいうえおん，编码只有 1 个字母）的权重。
#
# 它们**必须留在词库里**：既作 librime 组句的音节节点，又是 ingest() 校验用的
# 音节表成员。删掉会让含 a/n 音节的词整批失效——实测 72.6 万条会掉到 22 万条。
#
# 它们唯一的害处是：日语翻译器会拿单字母码切分组句，词库里只要有
# 「是=u、发=f、吗=m」这类**中文单键词条**，打入 ufm 就会被切成 u+f+m
# 组出「是发吗」。那条路径已由 ingest() 的「禁止单字母编码词条」硬约束堵死，
# 所以这里不必再靠低权重让位——给到与普通假名同级的 1000，
# 让 あ/い/う/え/お/ん 能正常出现在第一页。
SINGLE_KANA_WEIGHT = 1000
# 单键假名的片假名同伴（ア/イ/…）。略低，让平假名优先。
KATA_SINGLE_WEIGHT = 960
# 日语侧的单键编码（自检用）
SINGLE_KEY_CODES = {'a', 'i', 'u', 'e', 'o', 'n'}


def kana_section():
    """[(文字, 编码, 权重)] 全假名音节表（结果缓存，脚本里会被反复取用）"""
    if _KANA_SECTION_CACHE:
        return _KANA_SECTION_CACHE[0]
    entries = []
    particles = {'の', 'は', 'ん'}          # 高频助词提权
    # 基础清音/浊音。
    # 注意 len(code) == 1 的（あいうえおん）即使权重压到 60，
    # 也仍是可被组句使用的单键音节——所以真正的防线是 gen 里的
    # 「禁止单字母编码词条」硬约束 + lua/jp_lang.lua 过滤器，这里只是降权让位。
    for h, code in BASE.items():
        if h in ('ゐ', 'ゑ'):
            continue
        if len(code) == 1:
            w = SINGLE_KANA_WEIGHT          # あいうえおん：与普通假名同级
            kw = KATA_SINGLE_WEIGHT
        elif h in particles:
            w = 1200
            kw = 150
        else:
            w = 1000
            kw = 150
        entries.append((h, code, w))
        k = [k for k, hh in K2H.items() if hh == h]
        if k:
            entries.append((k[0], code, kw))
    # 拗音
    for b in 'きしちにひみりぎじびぴ':
        for s in 'ゃゅょ':
            code = yoon_code(b, s)
            if code:
                entries.append((b + s, code, 1200))
