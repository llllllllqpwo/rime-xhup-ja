# ---------------------------------------------------------------- 声母缩写
# 「只打声母」：一个字只按它的声母键就能出候选。
# 所以这里显式加一张单键表：zh→v、ch→i、sh→u（与小鹤一致），
# 其余声母就用字母本身。
#
# 为什么权重必须高于 1000/1200：
#   a/i/u/e/o/n 同时也是日语假名的**单键**编码（あいうえおん），
#   中文单键要压过它们才符合「打中文时单键出中文高频字」的预期。
#   日语侧的单键假名已按 SINGLE_KANA_WEIGHT 下调，两边配合才有这个效果。
#   这里只影响单键输入；打全码（wo/le/de）时中文侧照常用原词库权重。
# ---------------------------------------------------------------- 声母缩写（已废弃）
# 这里原本有一张 26 条的中文单键表（w=我、l=了、d=的…），权重 1140~1500。
#
# 已删除，原因：它们被写进 ja_romaji.dict.yaml 后，日语翻译器会把
# u/f/m 这类单字母码当作可组合的音节，于是打入 ufm 就被切成 u+f+m
# 组出「是发吗」，并带上日语的 ⟨JP⟩ 注释（用户实际撞上的bug）。
# 候选级过滤器拦不住，因为问题出在「切成音节」这一步就成立了。
#
# 现在单键输入的行为：
#   * 中文侧：rime-ice 自带的单键条目（w→我、l→了、d→的…）本来就有
#   * 日语侧：没有任何单键词条（见 ingest 里的硬约束），不会出假名
SHENG_MU = []



# ---------------------------------------------------------------- 词表读取
# 手工专名表的默认权重（表里省略第三列时使用）
LOCAL_DEFAULT_WEIGHT = 600


def load_tsv(path, default_weight=None):
    """读取 TSV 词表: 表记<TAB>假名读音[<TAB>权重]

    权重可省略（用 default_weight）。列数或权重非法时报行号并跳过，
    方便手工维护的 ja_words_local.tsv 出错时定位。
    """
    out = []
    with open(path, 'r', encoding='utf-8') as f:
        for lineno, line in enumerate(f, 1):
            line = line.rstrip('\n')
            if not line or line.startswith('#'):
                continue
            parts = line.split('\t')
            if len(parts) < 2 or not parts[0] or not parts[1]:
                sys.stderr.write(f'[警告] {path}:{lineno} 列数不足，跳过\n')
                continue
            surface, reading = parts[0], parts[1]
            if len(parts) >= 3 and parts[2].strip():
                try:
                    w = int(parts[2])
                except ValueError:
                    sys.stderr.write(f'[警告] {path}:{lineno} 权重非法({parts[2]!r})，跳过\n')
                    continue
            elif default_weight is not None:
                w = default_weight
            else:
                sys.stderr.write(f'[警告] {path}:{lineno} 缺少权重，跳过\n')
                continue
            out.append((surface, reading, w))
    return out


