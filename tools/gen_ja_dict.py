    for h, code in extra_sokuon:
        entries.append((h, code, 700))
    # 注意：这里**不能**过滤掉单字母编码的假名（あ→a、い→i、ん→n）。
    # 因为 ingest() 用本表的编码集合当 syllabary 做校验，
