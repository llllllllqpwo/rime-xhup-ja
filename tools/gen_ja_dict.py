# ---------------------------------------------------------------- 生成
def main():
    ap = argparse.ArgumentParser(description='生成 ja_romaji.dict.yaml')
    ap.add_argument('--extra', default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                    '..', 'ja_words_extra.tsv'),
                    help='扩展词库 TSV 路径；传 none 表示只用内置精选词')
    ap.add_argument('-o', '--output', default=None, help='输出文件（默认写到 stdout）')
    ap.add_argument('--extra-cap', type=int, default=450,
                    help='扩展词库的权重上限（默认 450，压在精选词之下、片假名之上）')
    ap.add_argument('--variant-min', type=int, default=470,
                    help='只为权重不低于该值的词生成假名变体（默认 470；设为 0 表示全都生成）')
    ap.add_argument('--variant-ratio', type=float, default=0.35,
                    help='假名变体的权重系数（默认 0.35）')
    ap.add_argument('--local', default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                    '..', 'ja_words_local.tsv'),
                    help='手工专名表 TSV（ACG 作品名/艺名等）；传 none 表示不用')
    ap.add_argument('--no-shengmu', action='store_true',
                    help='不写入「只打声母」单键表（用于验证简拼能否独立支撑单键输入）')
    args = ap.parse_args()

    entries = {}
    # 精选词锁定的 (表记, 读音) -> 权重。锁定值不参与 max 比较：
    # 批量库与自动变体一律不得覆盖，否则「何故→なぜ(175)」这种自动变体
    # 会把手工调过的「なぜ(600)」压下去（两者表记+编码相同）。
    pinned = {}

    def add(text, code, weight, key=None):
        k = (text, code)
        if key is not None and key in pinned:
            return
        if k in entries:
            entries[k] = max(entries[k], weight)
        else:
            entries[k] = weight

    kana_entries = kana_section()
    for text, code, w in kana_entries:
        add(text, code, w)

    # 「只打声母」单键表。
    # 用 add() 而非锁定写入：这里只是给中文侧一个单键入口，
    # 不该影响任何全码条目的权重。
    # 注意这些编码同时是日语单键假名（a/i/u/e/o/n）的编码，
    # 权重高于 SINGLE_KANA_WEIGHT，所以单键优先出中文。
    for code, text, w in ([] if args.no_shengmu else SHENG_MU):
        add(text, code, w)

    # syllabary 用于校验
    syllabary = {code for _, code, _ in kana_entries}

    stat = {'curated': 0, 'curated_drop': 0, 'extra': 0, 'extra_drop': 0,
            'local': 0, 'local_drop': 0, 'variant': 0}

    def ingest(pool, label, cap, pin=False):
        """把 (表记, 读音, 权重) 池子转成词典条目

        cap —— 该池子的权重上限，用来把批量导入的扩展词整体压在精选词之下
        （精选词是手工调过的，含 ない=800、から=800、七=400 这类低分高频词）。
        pin —— 该池子权重为锁定值，写入 pinned 后任何其他池子都不能覆盖。
        """
        if cap is None:
            cap = 999
        drop_key = label + '_drop'
        seen = set()
        variants = []
        for surface, reading, w in pool:
            if (surface, reading) in seen:      # 同一词库内的重复条目只算一次
                continue
            seen.add((surface, reading))
            if surface == reading and len(moras(reading)) <= 1:
                # 单音节假名（あ/か/きゃ）已在音节表里，重复入库只会刷屏；
                # 多音节假名词（なぜ/ここ/ありがとう）必须保留，
                # 否则整串只能退化成逐音节候选，词组匹配会失效
                continue
            code = romaji_code(reading)
            if code is None:
                stat[drop_key] += 1
                continue
            # 【硬性约束】不允许「单字母编码」的词条进词库。
            # 原因：日语翻译器会把一个输入串切成音节再组合，
            # 若词库里存在单字母码（如 我=w、是=u、发=f、吗=m），
            # 打入 ufm 就会被切成 u+f+m 组出「是发吗」，
            # 而且候选会带上日语的 ⟨JP⟩ 注释（实测用户就是这么撞上的）。
            # 单键输入应当只由中文侧和 jp_lang.lua 过滤器负责。
            if len(code.replace(' ', '')) <= 1:
                stat[drop_key] += 1
                continue
            bad = [s for s in code.split() if s not in syllabary]
            if bad:
                stat[drop_key] += 1
                continue
            key = (surface, reading)
            if key in pinned and not pin:
                stat[label] += 1
                continue                        # 精选词已锁定该条，跳过即可
            # 词条权重严格压在假名音节表之下（1000/1200 留给假名与助词）
            w = min(cap, w)
            if pin:
                pinned[key] = w
                entries[(surface, code)] = w    # 锁定值直接覆盖
            else:
                add(surface, code, w)
            stat[label] += 1
            # 汉字/假名混合表记 → 附带假名变体（先收集，等直接词条全部入库后再加，
            # 否则靠前的词（何故→なぜ=175）会把靠后的直接词条（なぜ=600）压掉）
            if surface != reading and not all(c in 'ゃゅょぁぃぅぇぉっー' or c in KATA or c in BASE
                                              for c in surface):
                variants.append((reading, code, w))

        # 假名变体。
        # 阈值只管批量词库：几十万汉字表记的变体用处有限，
        # 却会让词典体积翻倍（实测 51 万个变体 ≈ 20 MB）。
        # 精选词的变体一律生成——「がんばって(280)」这类正是手调过的低分高频词，
        # 用统一阈值会把它们一起误伤（实测踩过）。
        for reading, code, vw0 in variants:
            if not pin and vw0 < args.variant_min:
                continue
            vw = max(1, int(vw0 * args.variant_ratio))
            stat['variant'] += 1
            if pin:
                if entries.get((reading, code), 0) < vw:
                    entries[(reading, code)] = vw
                pinned[(reading, reading)] = entries[(reading, code)]
            else:
                add(reading, code, vw, key=(reading, reading))

    # 批量词库先入池（总体权重更低），随后手工表与精选词锁定覆盖
    n_extra_total = 0
    if args.extra and args.extra.lower() != 'none':
        if os.path.exists(args.extra):
            pool = load_tsv(args.extra)
            n_extra_total = len(pool)
            ingest(pool, 'extra', args.extra_cap)
        else:
            sys.stderr.write(f'[警告] 扩展词库不存在，跳过: {args.extra}\n')

    # 手工专名表：ACG 作品名、艺人艺名这类开源词库查不到的专名。
    # 权重是手挑的，按锁定处理，批量库不得覆盖。
    n_local = 0
    if args.local and args.local.lower() != 'none':
        if os.path.exists(args.local):
            lpool = load_tsv(args.local, default_weight=LOCAL_DEFAULT_WEIGHT)
            n_local = len(lpool)
            ingest(lpool, 'local', 999, pin=True)
        else:
            sys.stderr.write(f'[警告] 手工专名表不存在，跳过: {args.local}\n')

    ingest(WORDS, 'curated', 999, pin=True)

    # 输出
    out = open(args.output, 'w', encoding='utf-8') if args.output else sys.stdout
    out.write('# encoding: utf-8\n')
    out.write('#\n')
    out.write('# 日语罗马字词典 —— 「小鹤双拼·日语混输」方案 (xhup_ja)\n')
    out.write('# 由 tools/gen_ja_dict.py 生成，请勿手工编辑（改词请改生成器后重新生成）\n')
    out.write('# 词条: %d 个（含假名音节表）\n' % len(entries))
    out.write('#\n')
    out.write('# 构成: 假名音节表 %d + 精选词 %d + 手工专名 %d + 扩展词库 %d（另有 %d 个假名变体）\n'
              % (len(kana_entries), stat['curated'], stat['local'], stat['extra'], stat['variant']))
    out.write('# 因读音无法转码或音节不在音节表而丢弃: 精选 %d / 手工专名 %d / 扩展 %d\n'
              % (stat['curated_drop'], stat['local_drop'], stat['extra_drop']))
    out.write('#\n')
    out.write('# 注意: 本文件里 %d 条**单键**条目（w=我、l=了、d=的、b=吧…）是中文「只打声母」\n'
              % len(SHENG_MU))
    out.write('#   缩写，不是日语词。它们借放这里只是为了部署省一个文件——\n')
    out.write('#   日语单键假名（あいうえおん）已从 1000 降到 %d 让位，\n' % SINGLE_KANA_WEIGHT)
    out.write('#   而 か/し/の 这些两键以上假名完全不受影响。\n')
    out.write('#\n')
    out.write('# 词条来源: 精选词与手工专名见 tools/gen_ja_dict.py 与 ja_words_local.tsv\n')
    out.write('#   扩展词库: JMdict 常用词 + Mozc 开源词库 + jmnedict 专有名词 + kanjidic2\n')
    out.write('#   JMdict / jmnedict / kanjidic2  © EDRDG  CC-BY-SA 4.0\n')
    out.write('#   Mozc 开源词库（含 IPAdic / NAIST） BSD-3-Clause\n')
    out.write('#   FrequencyWords  MIT（仅用于判断表记可信度）\n')
    out.write('#\n')
    out.write('# 权重设计（经 librime 实测调校）:\n')
    out.write('#   助词 の/は/ん 1200 > 拗音 1200 > 平假名 1000\n')
    out.write('#   > 精选词 300~999 > 扩展词库 300~%d > 片假名 150\n' % args.extra_cap)
    out.write('#   → か 排在 卡 后、生僻字前；片假名单字不与中文抢位\n')
    out.write('---\n')
    out.write('name: ja_romaji\n')
    out.write('version: "1.0"\n')
    out.write('sort: by_weight\n')
    out.write('use_preset_vocabulary: false\n')
    out.write('...\n\n')
    for (text, code), w in sorted(entries.items(),
                                  key=lambda kv: (-kv[1], len(kv[0][0]), kv[0][0], kv[0][1])):
        out.write(f'{text}\t{code}\t{w}\n')
    if args.output:
        out.close()

    if stat['curated_drop']:
        sys.stderr.write(f'[警告] 精选词有 {stat["curated_drop"]} 条被丢弃\n')
    sys.stderr.write(
        f'完成: {len(entries)} 词条 '
        f'(音节表 {len(kana_entries)} / 精选 {stat["curated"]} / 扩展 {stat["extra"]}'
        + (f'（读入 {n_extra_total}）' if n_extra_total else '')
        + f' / 丢弃 {stat["curated_drop"] + stat["extra_drop"]})\n')

if __name__ == '__main__':
    main()
